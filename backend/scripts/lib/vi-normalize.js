function applyReplacements(input, pairs) {
  let next = String(input ?? "");
  for (const [from, to] of pairs) {
    next = next.replaceAll(from, to);
  }
  return next;
}

export function viText(input) {
  return applyReplacements(applyReplacements(input, NAME_REPLACEMENTS), REPLACEMENTS);
}

export function viObjectStrings(value) {
  if (Array.isArray(value)) {
    return value.map(viObjectStrings);
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, viObjectStrings(item)])
    );
  }
  if (typeof value === "string") {
    return viText(value);
  }
  return value;
}
